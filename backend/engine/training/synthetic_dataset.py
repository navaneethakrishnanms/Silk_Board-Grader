"""Build a SYNTHETIC dataset.zip in the exact layout of GET /api/v1/export/dataset.zip (brief Section 10.2).

Used only to prove the training chain end to end before real expert-graded data exists.
Every report produced from it is titled "SYNTHETIC — not real accuracy".

    python -m training.synthetic_dataset --out runs/synthetic_dataset.zip --records 160

Labels are *simulated* assessors: a hidden "visual" grade = ISO formula on the true colour shift
+ a bias (dark shades read better, printed fabrics and cotton stains read worse) + noise;
assessor A and B grade it independently; any A != B goes to assessor C (third-assessor rule).
"""

from __future__ import annotations

import argparse
import csv
import io
import json
import sys
import zipfile
from pathlib import Path

import cv2
import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from silkgrade_engine.colour import delta_e_ab, delta_e_f  # noqa: E402
from silkgrade_engine.iso_grading import change_rating, half_grade, stain_rating  # noqa: E402
from tools.make_synthetic import compose, fabric_rect, plain, polygon_of, printed, printed_layout, sensor_noise, texture  # noqa: E402

META_COLUMNS = [
    "test_id",
    "sample_id",
    "batch_id",
    "fabric_type",
    "construction",
    "base_shade",
    "dominant_hue",
    "dye_class",
    "wash_method",
    "adj1_fibre",
    "adj2_fibre",
    "device_before",
    "device_after",
    "ref_card",
    "grade_change_overall",
    "grade_change_ground",
    "grade_change_worst",
    "grade_stain_adj1",
    "grade_stain_adj2",
    *[f"assessor{a}_{k}" for a in "ABC" for k in ("change_overall", "stain_adj1", "stain_adj2")],
    "engine_version",
]
SHADES = {"light": (70.0, 85.0), "medium": (45.0, 62.0), "dark": (22.0, 38.0)}
CONSTRUCTIONS = ["satin", "crepe", "georgette", "plain weave"]


def _png(rgb: np.ndarray) -> bytes:
    u8 = np.clip(rgb * 255.0 + 0.5, 0, 255).astype(np.uint8)
    ok, buf = cv2.imencode(".png", u8[:, :, ::-1])
    assert ok
    return buf.tobytes()


def _assessors(visual: float, rng: np.random.Generator) -> dict:
    a = half_grade(visual + rng.normal(0, 0.28))
    b = half_grade(visual + rng.normal(0, 0.28))
    c = half_grade(visual + rng.normal(0, 0.15)) if a != b else None
    return {"assessor_A": a, "assessor_B": b, "assessor_C": c, "consensus": a if a == b else c, "state": "LABELLED"}


def build(out: Path, n_records: int = 160, seed: int = 7, size: tuple[int, int] = (480, 360)) -> Path:
    rng = np.random.default_rng(seed)
    w, h = size
    rect = fabric_rect(h, w)
    poly = polygon_of(rect)
    meta_rows: list[list] = []
    out.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr(
            "dataset/SYNTHETIC.txt", "SYNTHETIC dataset generated by training/synthetic_dataset.py — not real expert data.\n"
        )
        n_samples = max(2, int(n_records * 0.8))
        for i in range(n_records):
            test_id = f"syn-{i:05d}"
            sample_id = f"SYN-{int(rng.integers(0, n_samples)):04d}"  # some samples tested twice
            shade = str(rng.choice(list(SHADES)))
            printed_fab = bool(rng.random() < 0.25)
            construction = str(rng.choice(CONSTRUCTIONS))
            device_b = str(rng.choice(["Pixel 8", "iPhone 15"]))
            device_a = device_b if rng.random() > 0.1 else ("iPhone 15" if device_b == "Pixel 8" else "Pixel 8")
            L0 = rng.uniform(*SHADES[shade])
            a0, b0 = rng.normal(0, 25, 2)
            base = np.array([L0, a0, b0])
            # colour change: magnitude spread across the grade scale
            mag = float(rng.choice([0.2, 0.8, 1.5, 2.5, 3.5, 5.0, 7.0, 10.0])) * rng.uniform(0.7, 1.3)
            direction = rng.normal(0, 1, 3)
            direction[0] = abs(direction[0]) * rng.choice([1, 1, -1])  # mostly fading (lighter)
            direction /= np.linalg.norm(direction)
            after = base + direction * mag
            seed_i = int(rng.integers(0, 1_000_000))
            tex = texture(h, w, seed_i, amp=1.4)
            if printed_fab:
                labels = printed_layout(h, w, seed=seed_i % 97)
                motif = np.array([min(L0 + 20, 90), -a0 * 0.8, b0 * 0.5])
                spec_b = printed([base, motif, np.array([80.0, 5, 60])], labels)
                spec_a = printed([base + (after - base) * 0.3, motif + (after - base), np.array([80.0, 5, 60])], labels)
                eff_after = base + (after - base) * 0.6  # what an assessor perceives overall
            else:
                spec_b, spec_a = plain(base, h, w), plain(after, h, w)
                eff_after = after
            imgs = {
                "specimen_before": compose(spec_b, rect, h, w, tex, sensor_noise(h, w, seed_i + 1)),
                "specimen_after": compose(spec_a, rect, h, w, tex, sensor_noise(h, w, seed_i + 2)),
            }
            stains = {}
            for k, fibre, white in (("adj1", "silk", (93.0, -0.3, 2.0)), ("adj2", "cotton", (94.0, 0.0, 1.0))):
                smag = float(rng.choice([0.0, 1.5, 3.5, 6.0, 9.0, 13.0, 18.0])) * rng.uniform(0.7, 1.3)
                tint = np.array([-1.0, rng.normal(0, 0.4), rng.normal(0.3, 0.4)])
                tint /= np.linalg.norm(tint)
                stained = np.array(white) + tint * smag
                stains[k] = (np.array(white), stained, fibre)
                imgs[f"{k}_before"] = compose(
                    plain(white, h, w), rect, h, w, texture(h, w, seed_i + 3, 1.0), sensor_noise(h, w, seed_i + 4)
                )
                imgs[f"{k}_after"] = compose(
                    plain(stained, h, w), rect, h, w, texture(h, w, seed_i + 5, 1.0), sensor_noise(h, w, seed_i + 6)
                )

            # hidden "visual" grades -> simulated blind assessors
            bias_change = 0.2 * (shade == "dark") - 0.15 * printed_fab
            dEF, _ = delta_e_f(base, eff_after)
            v_change = change_rating(float(dEF)) + bias_change + rng.normal(0, 0.15)
            lab = {"CHANGE_OVERALL": _assessors(v_change, rng)}
            for k, (wb, wa, fibre) in stains.items():
                dE = float(delta_e_ab(wb, wa))
                v = stain_rating(dE, float(wa[0] - wb[0])) - (0.2 if fibre == "cotton" else 0.0) + rng.normal(0, 0.15)
                lab[f"STAIN_{k.upper()}"] = _assessors(v, rng)
            lab["STAIN_WORST"] = {
                key: (
                    min(x for x in (lab["STAIN_ADJ1"][key], lab["STAIN_ADJ2"][key]) if x is not None)
                    if lab["STAIN_ADJ1"][key] is not None and lab["STAIN_ADJ2"][key] is not None
                    else None
                )
                for key in ("assessor_A", "assessor_B", "consensus")
            }
            lab["STAIN_WORST"]["assessor_C"] = None
            lab["STAIN_WORST"]["state"] = "LABELLED"

            rec = f"dataset/records/{sample_id}__{test_id}/"
            for name, rgb in imgs.items():
                z.writestr(f"{rec}{name}.png", _png(rgb))
            regions = {
                "images": [
                    {
                        "image_role": f"{p.upper()}_{s.upper()}",
                        "side": s,
                        "regions": [{"piece": p.upper(), "polygon": poly, "auto_detected": False}],
                    }
                    for p in ("specimen", "adj1", "adj2")
                    for s in ("before", "after")
                ]
            }
            z.writestr(f"{rec}regions.json", json.dumps(regions))
            z.writestr(
                f"{rec}features.json",
                json.dumps(
                    {
                        "test_id": test_id,
                        "fabric_type": "PRINTED" if printed_fab else "PLAIN",
                        "grades": {},
                        "note": "recomputed by training.run",
                    }
                ),
            )
            z.writestr(f"{rec}labels.json", json.dumps({"test_id": test_id, "grades": lab}))
            meta_rows.append(
                [
                    test_id,
                    sample_id,
                    "SYN",
                    "PRINTED" if printed_fab else "PLAIN",
                    construction,
                    shade,
                    "",
                    "",
                    "ISO 105-C10 A",
                    "silk",
                    "cotton",
                    device_b,
                    device_a,
                    False,
                    lab["CHANGE_OVERALL"]["consensus"],
                    "",
                    "",
                    lab["STAIN_ADJ1"]["consensus"],
                    lab["STAIN_ADJ2"]["consensus"],
                    *[lab[k][f"assessor_{a}"] for a in "ABC" for k in ("CHANGE_OVERALL", "STAIN_ADJ1", "STAIN_ADJ2")],
                    "synthetic",
                ]
            )
        buf = io.StringIO()
        wr = csv.writer(buf)
        wr.writerow(META_COLUMNS)
        wr.writerows(meta_rows)
        z.writestr("dataset/metadata.csv", buf.getvalue())
        z.writestr("dataset/splits.csv", "test_id,split\n")
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", required=True)
    ap.add_argument("--records", type=int, default=160)
    ap.add_argument("--seed", type=int, default=7)
    a = ap.parse_args()
    p = build(Path(a.out), a.records, a.seed)
    print(f"wrote SYNTHETIC dataset with {a.records} records to {p}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
